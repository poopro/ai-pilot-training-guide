def blob(path):
    b = base64.b64encode(Path(path).read_bytes()).decode()
    lines = [b[i:i + 100] for i in range(0, len(b), 100)]
    return "('' \n" + '\n'.join("    '%s'" % ln for ln in lines) + ')'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ridge', required=True)
    ap.add_argument('--mlp', default=None)
    ap.add_argument('--out', default=str(HERE / 'portable' / 'fighter_opt.py'))
    a = ap.parse_args()
    feats = FEATS[FEATS.index('def _wrap'):FEATS.index('def make_token')].rstrip()
    feats = 'FEAT_DIM = 27\n\n\n' + feats
    blobs = "    'ridge': %s," % blob(a.ridge)
    if a.mlp:
        blobs += "\n    'mlp': %s," % blob(a.mlp)
    src = TEMPLATE % dict(FEATS=feats.replace('%', '%%'), BLOBS=blobs)
    src = src.replace('%%', '%')
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(src, encoding='utf-8')
    compile(src, a.out, 'exec')
    print('wrote', a.out, len(src), 'bytes')


if __name__ == '__main__':
    main()
