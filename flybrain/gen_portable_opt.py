"""Generate portable/fighter_opt.py: the option tactician (raw 27 features + EMA -> ridge / MLP head -> commit LEAD etc. for 2 s,
only when the enemy is within 3.5 km) as ONE file for the CPU player.  numpy + the official modules + your portable/fighter.py only.

  python gen_portable_opt.py --ridge ro/opt_b1_frozen.feat.npz --mlp ro/opt_mlp_v3.npz  --out portable/fighter_opt.py

Profiles (build(name), falls back to fighter.build for everything else):
   opt_ridge            tactician (ridge head) on top of  base_t3   (frozen pursuit + shield v3)
   opt_ridge:tuned      ... on top of your tuned pursuit
   opt_mlp[:tuned]      same with the MLP head
   opt_<head>[:base][:tau=<x>][:zone=<m>][:hold=<n>]   optional overrides
The readout weights are embedded (base64 of the .npz), nothing is read from disk at run time.
"""
